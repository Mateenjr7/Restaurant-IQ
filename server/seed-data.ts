// Deterministically generate 60-day realistic daily sales history for forecasting
export function generateDailySalesHistory(
  baseDaily: number,
  trend: 'surging' | 'steady' | 'softening'
) {
  const history: Array<{ date: string; dayOfWeek: string; orders: number; revenue: number }> = [];
  const dayNames = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
  // Sunday peak, Friday/Saturday dinner surges, Monday dip
  const dayMultipliers = [1.35, 0.76, 0.82, 0.90, 1.05, 1.42, 1.54];
  const anchorDate = new Date('2026-10-20T12:00:00Z');

  for (let i = 60; i >= 1; i--) {
    const d = new Date(anchorDate);
    d.setDate(anchorDate.getDate() - i);
    const dayIdx = d.getDay();
    // Deterministic pseudo-noise
    const wave = Math.sin(i * 0.9 + baseDaily) * 0.10;
    const trendMultiplier =
      trend === 'surging'
        ? 0.94 + (60 - i) * (0.16 / 60)
        : trend === 'softening'
        ? 1.06 - (60 - i) * (0.14 / 60)
        : 1.0;

    const orders = Math.max(
      4,
      Math.round(baseDaily * dayMultipliers[dayIdx] * trendMultiplier * (1 + wave))
    );
    history.push({
      date: d.toISOString().split('T')[0],
      dayOfWeek: dayNames[dayIdx],
      orders,
      revenue: orders * 320,
    });
  }
  return history;
}

